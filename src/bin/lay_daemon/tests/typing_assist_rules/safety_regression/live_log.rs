#[test]
fn typing_assist_keeps_live_log_good_repairs() {
    for (input, expected) in [
        ("смтори ", "смотри "),
        ("спсика ", "списка "),
        ("дургие ", "другие "),
        ("нилинейная ", "нелинейная "),
        ("провблему ", "проблему "),
        ("спаибо ", "спасибо "),
        ("свойсва ", "свойства "),
        ("зпаушил ", "запушил "),
        ("там недоказно ", "там недоказано "),
        ("не раотает ", "не работает "),
        ("тоест ", "то есть "),
        ("датасет сначало ", "датасет сначала "),
        ("а двай ", "а давай "),
        ("с мониторм ", "с монитором "),
        ("Дальшне ", "Дальше "),
        ("связывания этоне ", "связывания это не "),
        ("работае понимание ", "работает понимание "),
        ("Друдочек ", "Дружочек "),
        ("вопросики позадовать ", "вопросики позадавать "),
        ("Суша тоде ", "Суша тоже "),
        ("нормальный делеай ", "нормальный делай "),
        ("за воопрос ", "за вопрос "),
        ("так готора ", "так готово "),
        ("комфортно сделат ", "комфортно сделать "),
        ("выполни изменнения ", "выполни изменения "),
        ("надо сжимат ", "надо сжимать "),
        ("хоршо ", "хорошо "),
        ("не заню ", "не знаю "),
        ("будет сльный ", "будет сильный "),
        ("работы помошники ", "работы помощники "),
        ("целью помотерть ", "целью посмотреть "),
        ("в переспективе? ", "в перспективе? "),
        ("разбор арххитекры ", "разбор архитектуры "),
    ] {
        assert_eq!(
            select_typing_assist_exact(input),
            Some(expected.to_string()),
            "input={input:?}"
        );
    }
}
